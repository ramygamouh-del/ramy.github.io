function applyLang(lang){
  document.documentElement.setAttribute('data-lang', lang);
  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key = el.getAttribute('data-i18n');
    if(I18N[lang][key]) el.lastChild && el.querySelector('svg') ? (el.childNodes[el.childNodes.length-1].textContent = ' ' + I18N[lang][key]) : (el.textContent = I18N[lang][key]);
  });
  document.querySelectorAll('#langswitch button').forEach(b=>{
    b.classList.toggle('active', b.dataset.setlang === lang);
  });
  localStorage.setItem('ramy-lang', lang);
}
document.getElementById('langswitch').addEventListener('click', e=>{
  const btn = e.target.closest('button');
  if(!btn) return;
  applyLang(btn.dataset.setlang);
});

